"""Pack shared C++ imitation records into per-game shards for train.py.

  python -B -X utf8 bots/main/zero/tools/pack.py [--jobs 16] [--keep]
  python -B bots/main/zero/tools/pack.py --exact INPUTS.jsonl.gz [--pack-dir .cache/main/zero/exact/pack]

Exact mode preserves chronological source inputs and separate internal annotations. It publishes a shard
only when the native representation coverage gate passes. Otherwise it writes a coverage audit and exits
nonzero. Categorical labels are int8; priority and quantity keep signed int32 source labels.

For every .cache/main/zero/text/<match>.txt without a shard: runs replay_obs.exe (.bin next to it), writes
.cache/main/zero/pack/games/<match>.npz and, unless --keep, deletes the .txt and .bin (both regenerable from the
decoded replay). A shard holds per head h (name prefix "<head>_"): state f16 [N, 48], phi f16 [N, C, kphi]
(zero-padded to the game's largest set), n int8, label int8, team int8, won int8 (1 win, 0 loss, -1 unknown),
round int16. Scalar ranged_omitted, ranged_move_attack, and ranged_repeated counts record excluded complex
ranged turns. train.py concatenates the shards.
pack/manifest.json binds all shards to the reader executable, feature sources, and head schema; a changed
producer requires regenerating into an empty games directory.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import uuid
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[4]
TEXT = ROOT / '.cache/main/zero/text'
SHARDS = ROOT / '.cache/main/zero/pack/games'
TOOL = ROOT / '.cache/main/zero/replay_obs.exe'
HEADS = ['goal', 'step', 'attack', 'cast0', 'cast1', 'shop', 'draft', 'tail', 'ranged', 'action', 'aux', 'priority', 'quantity']
KPHI = [24, 24, 16, 24, 24, 16, 24, 16, 24, 24, 24, 4, 4]
KSTATE = 48
PACK_SCHEMA = 8  # explicit fact-known flags and qualified eligible-policy coverage (all raw inputs retained)
COVERAGE_SCOPE = 'source_reference_eligible_policy'
COVERAGE_CONTRACT = {
    'scope': COVERAGE_SCOPE,
    'nonpolicy': ['kind7_carrier', 'kind26_fuel_boundary'],
    'unrecoverable_intent': ['kind23_inverse_ambiguous_intent'],
    'requires': ['all_raw_inputs_retained', 'all_other_inputs_labelled', 'all_selected_stages_present',
                 'complete_source_facts', 'no_affected_capability_limits', 'no_unknown_commands'],
    'runtime_path_fidelity': 'separate_pending_contract',
}
MANIFEST = SHARDS.parent / 'manifest.json'
SOURCES = [
    'tools/replay_obs.cpp',
    'src/core/cand.h', 'src/core/cand.cpp',
    'src/core/obs.h', 'src/core/obs.cpp',
    'src/core/map.h', 'src/core/map.cpp',
    'src/core/moves.h', 'src/core/moves.cpp',
    'src/core/rules.h', 'src/core/rules.cpp',
    'src/core/catalog.h', 'src/core/catalog.cpp', 'src/core/catalog_data.h',
]


def game_shards(pack_dir=None):
    directory = Path(pack_dir) / 'games' if pack_dir is not None else SHARDS
    return sorted(p for p in directory.glob('*.npz') if not p.name.endswith('.tmp.npz'))


def provenance(exact=False):
    def sha256(path):
        return hashlib.sha256(path.read_bytes()).hexdigest()
    sources = SOURCES if not exact else [
        p for p in SOURCES if p != 'tools/replay_obs.cpp'
    ] + ['src/core/action.h', 'src/core/action.cpp', 'src/core/utility.h', 'src/core/utility.cpp', 'src/core/plan.h', 'src/core/plan.cpp', 'src/core/draft_facts.h', 'src/core/draft_facts.cpp', 'tools/exact_records.cpp',
         'tools/exact_records.py', 'tools/exact_export.py', 'tools/pack.py']
    reader = ROOT / '.cache/main/zero/exact_records.exe' if exact else TOOL
    return {
        'schema': PACK_SCHEMA,
        'producer': 'exact-inputs' if exact else 'approximate-rounds',
        'heads': HEADS,
        'kphi': KPHI,
        'reader_sha256': sha256(reader),
        'source_sha256': {p: sha256(ROOT / 'bots/main/zero' / p) for p in sources},
        **({'coverage_contract': COVERAGE_CONTRACT} if exact else {}),
    }


def verify_manifest(create=False, pack_dir=None, exact=False):
    """Refuse mixtures of records generated by different readers or feature definitions."""
    manifest = Path(pack_dir) / 'manifest.json' if pack_dir is not None else MANIFEST
    current = provenance(exact=exact)
    if create and not game_shards(pack_dir):
        manifest.parent.mkdir(parents=True, exist_ok=True)
        manifest.write_text(json.dumps(current, indent=2) + '\n', encoding='utf-8')
        return
    if not manifest.is_file():
        raise SystemExit('packed records have no provenance manifest; regenerate into an empty games directory')
    if json.loads(manifest.read_text(encoding='utf-8')) != current:
        raise SystemExit('packed-record provenance differs from the current reader, sources, or schema; regenerate into an empty games directory')


def write_records(records, out: Path, metadata=None):
    """Write native-built features only; Python pads/transports arrays and adds provenance metadata."""
    per: dict[int, list] = {}
    for rec in records:
        per.setdefault(rec[0], []).append(rec)
    arrays = {'schema': np.array(PACK_SCHEMA, dtype=np.int32), **(metadata or {})}
    for h, recs in per.items():
        name = HEADS[h]
        count, width = len(recs), max(r[1] for r in recs)
        phi = np.zeros((count, width, KPHI[h]), dtype=np.float16)
        for i, rec in enumerate(recs):
            phi[i, :rec[1]] = rec[7]
        arrays[f'{name}_state'] = np.array([r[6] for r in recs], dtype=np.float16)
        arrays[f'{name}_phi'] = phi
        if not np.isfinite(arrays[f'{name}_state']).all() or not np.isfinite(phi).all():
            raise ValueError(f'{name}: float16 storage cannot represent these native features finitely')
        for key, index, dtype in [('n', 1, np.int8), ('label', 2, np.int32 if name in ('priority', 'quantity') else np.int8), ('team', 3, np.int8),
                                   ('round', 4, np.int16), ('won', 5, np.int8)]:
            arrays[f'{name}_{key}'] = np.array([r[index] for r in recs], dtype=dtype)
        if all(len(r) >= 10 for r in recs):
            arrays[f'{name}_sequence'] = np.array([r[8] for r in recs], dtype=np.int32)
            arrays[f'{name}_input'] = np.array([r[9] for r in recs], dtype=np.int32)
            arrays[f'{name}_annotation'] = np.array([r[8] < 0 for r in recs], dtype=np.int8)
    out.parent.mkdir(parents=True, exist_ok=True)
    temporary = out.with_name(f'{out.stem}.{uuid.uuid4().hex}.tmp.npz')
    np.savez_compressed(temporary, **arrays)
    temporary.replace(out)


def validate_exact_coverage(coverage):
    """Exact accepted exclusions never hide an unknown command or an incomplete source descriptor."""
    if not coverage.get('coverage_pass'):
        return False
    def count(key):
        value = coverage.get(key)
        if type(value) is not int or value < 0:
            raise ValueError(f'exact coverage has invalid {key}')
        return value
    if (coverage.get('schema') != 'zero-exact-records/v2' or coverage.get('coverage_scope') != COVERAGE_SCOPE
            or coverage.get('source_reference_coverage_pass') is not True or coverage.get('source_facts_complete') is not True):
        raise ValueError('exact coverage lacks the qualified source/reference contract')
    excluded = 0
    for field, permitted in [('nonpolicy_inputs', COVERAGE_CONTRACT['nonpolicy']),
                              ('unrecoverable_intent_inputs', COVERAGE_CONTRACT['unrecoverable_intent'])]:
        reasons = coverage.get(field)
        if not isinstance(reasons, dict) or set(reasons) - set(permitted):
            raise ValueError(f'exact coverage has unknown exclusions in {field}')
        if any(type(value) is not int or value < 0 for value in reasons.values()):
            raise ValueError(f'exact coverage has invalid exclusion counts in {field}')
        excluded += sum(reasons.values())
    raw, eligible, labelled = count('inputs'), count('eligible_policy_inputs'), count('eligible_policy_labelled_inputs')
    if (count('raw_retained_inputs') != raw or count('raw_source_labelled_inputs') != labelled
            or count('excluded_inputs') != excluded or eligible + excluded != raw or eligible != labelled
            or count('labelled_inputs') + count('draft_labelled_inputs') != labelled
            or count('draft_pick_inputs') != count('draft_labelled_inputs')
            or count('utility_ward_complete_inputs') != count('gameplay_inputs')
            or count('utility_consume_complete_inputs') != count('gameplay_inputs')
            or any(coverage.get(key) != {} for key in ('failures', 'annotation_failures', 'utility_affected_limits'))):
        raise ValueError('exact coverage pass contradicts retained inputs, eligible labels, or complete source facts')
    return True


def exact_shard(source: Path, pack_dir: Path, timeout=120):
    """Audit one chronological export; publish a shard only after exact representation coverage passes."""
    import exact_records
    sys.path.insert(0, str(ROOT / 'tools/arena'))
    import compiled_runner as native

    source, pack_dir = source.resolve(strict=True), pack_dir.resolve()
    if not pack_dir.is_relative_to((ROOT / '.cache/main/zero').resolve()):
        raise ValueError('exact packing output must stay inside this owner\'s scratch directory')
    verify_manifest(create=True, pack_dir=pack_dir, exact=True)
    work = pack_dir / 'work' / uuid.uuid4().hex
    work.mkdir(parents=True)
    def clean_work():
        resolved = work.resolve(strict=True)
        if not resolved.is_relative_to((ROOT / '.cache/main/zero').resolve()):
            raise RuntimeError('unsafe native intermediate cleanup path')
        shutil.rmtree(resolved)  # regenerable owner scratch; qualified arrays/audits live outside this directory
    tokens, binary, coverage_path = work / 'inputs.tokens', work / 'records.bin', work / 'coverage.json'
    exported = exact_records.transport(source, tokens)
    match = exported['metadata'].get('match')
    game_id = match.get('matchId') if isinstance(match, dict) else match
    if not isinstance(game_id, str) or re.fullmatch(r'[A-Za-z0-9_-]{1,128}', game_id) is None:
        raise ValueError('export has no safe stable match identity')
    out = pack_dir / 'games' / f'{game_id}.npz'
    if out.is_file():
        with np.load(out) as existing:
            if str(existing.get('source_sha256', '')) != exported['source_sha256']:
                raise ValueError('this match already has a different export/window; regenerate the exact dataset instead of duplicating one game')
        clean_work()
        return {'status': 'done', 'game': game_id}
    reader = ROOT / '.cache/main/zero/exact_records.exe'
    command = [str(reader), str(tokens), str(binary), str(coverage_path)]
    native_dir = work / 'native'
    native_dir.mkdir()
    execution = native._slotted_command(lambda _: command, ROOT, native_dir, timeout, jobs=1, minimum=1, poll=0.05)
    if execution['returncode'] or not execution.get('tree_exit_confirmed'):
        raise RuntimeError(f'exact reader failed: exit={execution["returncode"]}, tree_closed={execution.get("tree_exit_confirmed")}')
    coverage = json.loads(coverage_path.read_text(encoding='utf-8'))
    verify_manifest(pack_dir=pack_dir, exact=True)  # refuse source/executable changes during native production
    audit_export = {key: value for key, value in exported.items() if key != 'tokens'}
    audit = {'source_path': str(source), 'source_sha256': exported['source_sha256'], 'export': audit_export,
             'coverage': coverage, 'manifest': provenance(exact=True)}
    audit_path = pack_dir / 'coverage' / f'{game_id}.json'
    audit_path.parent.mkdir(parents=True, exist_ok=True)
    audit_tmp = audit_path.with_suffix('.tmp.json')
    audit_tmp.write_text(json.dumps(audit, indent=2) + '\n', encoding='utf-8')
    audit_tmp.replace(audit_path)
    if not validate_exact_coverage(coverage):
        clean_work()
        return {'status': 'coverage_failed', 'game': game_id, 'coverage': coverage, 'audit': str(audit_path)}
    records = read(binary, with_origin=True)
    if len(records) != coverage['records']:
        raise ValueError('native record count differs from its coverage report')
    write_records(records, out, {
        'source_sha256': np.array(exported['source_sha256']), 'game_id': np.array(game_id),
        'coverage_pass': np.array(1, dtype=np.int8), 'input_count': np.array(coverage['inputs'], dtype=np.int64),
        'coverage_scope': np.array(COVERAGE_SCOPE), 'source_facts_complete': np.array(1, dtype=np.int8),
        'eligible_policy_inputs': np.array(coverage['eligible_policy_inputs'], dtype=np.int64),
        'eligible_policy_labelled_inputs': np.array(coverage['eligible_policy_labelled_inputs'], dtype=np.int64),
        'excluded_inputs': np.array(coverage['excluded_inputs'], dtype=np.int64),
    })
    clean_work()
    return {'status': 'packed', 'game': game_id, 'records': coverage['records'], 'audit': str(audit_path)}


def read(path: Path, with_origin=False):
    data = path.read_bytes()
    view = memoryview(data)
    at, recs = 0, []
    while at + 36 <= len(data):
        hdr = np.frombuffer(view[at:at + 36], dtype=np.int32)
        head, n, label, kphi = int(hdr[0]), int(hdr[1]), int(hdr[2]), int(hdr[3])
        scalar = 0 <= head < len(HEADS) and HEADS[head] in ('priority', 'quantity')
        if not (0 <= head < len(HEADS) and 0 < n <= 24 and (scalar or 0 <= label < n) and kphi == KPHI[head]):
            raise ValueError(f'{path}: invalid record header at byte {at}: {hdr.tolist()}')
        if scalar and n != 1:
            raise ValueError(f'{path}: scalar heads require exactly one candidate')
        at += 36
        if at + 4 * (KSTATE + n * kphi) > len(data):
            raise ValueError(f'{path}: truncated record at byte {at - 36}')
        state = np.frombuffer(view[at:at + 4 * KSTATE], dtype=np.float32)
        at += 4 * KSTATE
        phi = np.frombuffer(view[at:at + 4 * n * kphi], dtype=np.float32).reshape(n, kphi)
        if HEADS[head] == 'priority' and not np.array_equal(phi, np.array([[1.0, 0.0, 0.0, 0.0]], dtype=np.float32)):
            raise ValueError(f'{path}: priority candidate must be constant and cannot contain its target')
        if HEADS[head] == 'quantity' and (label < 1 or not np.isfinite(phi).all() or phi[0, 0] != 1 or not 0 <= phi[0, 1] < 1 or phi[0, 2] <= 0 or phi[0, 3] <= 0):
            raise ValueError(f'{path}: invalid quantity source label or item/affordability facts')
        at += 4 * n * kphi
        record = (head, n, label, int(hdr[4]), int(hdr[5]), int(hdr[6]), state, phi)
        if with_origin:
            record += (int(hdr[7]), int(hdr[8]))
        recs.append(record)
    if at != len(data):
        raise ValueError(f'{path}: trailing {len(data) - at} bytes')
    return recs


def ranged_omissions(summary: str):
    match = re.search(r' \| ranged omitted ([0-9]+) \(move\+attack ([0-9]+), repeated actions ([0-9]+)\)\n?\Z', summary)
    if match is None:
        raise ValueError('replay reader summary is missing the required ranged omission counts')
    return {name: np.array(int(count), dtype=np.int64) for name, count in zip(
        ('ranged_omitted', 'ranged_move_attack', 'ranged_repeated'), match.groups())}


def shard(txt: Path, keep: bool) -> str:
    out = SHARDS / f'{txt.stem}.npz'
    if out.is_file():
        with np.load(out) as existing:
            if int(existing.get('schema', -1)) == PACK_SCHEMA:
                return 'done'
    bin_ = txt.with_suffix('.bin')
    p = subprocess.run([str(TOOL), str(txt), str(bin_)], capture_output=True, text=True)
    if p.returncode != 0:
        return 'failed'
    omissions = ranged_omissions(p.stdout)
    per: dict[int, list] = {}
    for rec in read(bin_):
        per.setdefault(rec[0], []).append(rec)
    arrays = {'schema': np.array(PACK_SCHEMA, dtype=np.int32), **omissions}
    for h, recs in per.items():
        name = HEADS[h]
        N, C = len(recs), max(r[1] for r in recs)
        phi = np.zeros((N, C, KPHI[h]), dtype=np.float16)
        for i, r in enumerate(recs):
            phi[i, :r[1]] = r[7]
        arrays[f'{name}_state'] = np.array([r[6] for r in recs], dtype=np.float16)
        arrays[f'{name}_phi'] = phi
        arrays[f'{name}_n'] = np.array([r[1] for r in recs], dtype=np.int8)
        arrays[f'{name}_label'] = np.array([r[2] for r in recs], dtype=np.int8)
        arrays[f'{name}_team'] = np.array([r[3] for r in recs], dtype=np.int8)
        arrays[f'{name}_round'] = np.array([r[4] for r in recs], dtype=np.int16)
        arrays[f'{name}_won'] = np.array([r[5] for r in recs], dtype=np.int8)
    tmp = out.with_suffix('.tmp.npz')
    np.savez_compressed(tmp, **arrays)
    tmp.replace(out)
    if not keep:
        txt.unlink()
        bin_.unlink()
    return 'packed'


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', type=int, default=16)
    ap.add_argument('--keep', action='store_true', help='keep the .txt/.bin intermediates')
    ap.add_argument('--exact', type=Path, help='audit and pack one ordered exact-export JSONL file')
    ap.add_argument('--pack-dir', type=Path, default=ROOT / '.cache/main/zero/exact/pack')
    ap.add_argument('--timeout', type=int, default=120)
    a = ap.parse_args()
    if a.exact:
        result = exact_shard(a.exact, a.pack_dir, a.timeout)
        print(json.dumps(result, sort_keys=True))
        raise SystemExit(2 if result['status'] == 'coverage_failed' else 0)
    SHARDS.mkdir(parents=True, exist_ok=True)
    verify_manifest(create=True)
    txts = sorted(TEXT.glob('*.txt'))
    with ThreadPoolExecutor(a.jobs) as ex:
        results = list(ex.map(lambda t: shard(t, a.keep), txts))
    print({k: results.count(k) for k in set(results)}, f'{len(game_shards())} shards')


if __name__ == '__main__':
    main()
