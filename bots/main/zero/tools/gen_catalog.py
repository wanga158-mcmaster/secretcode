"""Generate bots/main/zero/src/core/catalog_data.h from docs/reference/runtime-catalog.json (the pinned bundle's
rule data). Rerun on every bundle upgrade; the bot logs an error line if the live SDK designs disagree.

  python -B -X utf8 bots/main/zero/tools/gen_catalog.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
c = json.loads((ROOT / 'docs/reference/runtime-catalog.json').read_text(encoding='utf-8'))['result']
OUT = ROOT / 'bots/main/zero/src/core/catalog_data.h'


def f(v) -> str:
    s = repr(float(v))
    return (s if ('.' in s or 'e' in s) else s + '.0') + 'f'


def ability(a: dict) -> str:
    p = a.get('payload') or {}
    excl = 1 if (a.get('attributes', 0) & 1) else 0
    return ('{ ' + f"{a['kind']}, {a['targets']}, {'true' if excl else 'false'}, {a['cooldown']}, {f(p.get('range', 0))}, "
            f"{f(p.get('radius', 0))}, {f(p.get('modifier', 0))}, {f(p.get('duration', 0))}, "
            f"{'true' if p.get('enhanced_attack') else 'false'}" + ' }')


lines = ['#pragma once', '// Generated by bots/main/zero/tools/gen_catalog.py from docs/reference/runtime-catalog.json - do not edit.',
         '#include "catalog.h"', '', 'namespace zero::data {', '']
lines.append('inline constexpr ChampionDesign kChampions[] = {')
for ch in sorted(c['champions'], key=lambda x: x['type']):
    s = ch['stats']
    ab = ch['abilities'] + [{'kind': 0, 'targets': 0, 'cooldown': 0, 'payload': {}}] * (2 - len(ch['abilities']))
    lines.append(f"    {{ \"{ch['name']}\", {ch['type']}, {ch['passive']}, {ch['attack_type']}, {{ {ability(ab[0])}, {ability(ab[1])} }}, "
                 f"{f(s['vision_radius'])}, {f(s['base_move_speed'])}, {f(s['base_attack_range'])}, {f(s['base_health'])}, "
                 f"{f(s['health_growth'])}, {f(s['base_strength'])}, {f(s['strength_growth'])}, {f(s['base_focus'])}, "
                 f"{f(s['focus_growth'])}, {f(s.get('camp_damage_multiplier', 1))} }},")
lines.append('};')
lines.append('inline constexpr CampDesign kCamps[] = {')
for cp in sorted(c['camps'], key=lambda x: x['type']):
    s = cp['stats']
    lines.append(f"    {{ \"{cp['name']}\", {cp['type']}, {f(s['base_health'])}, {f(s['base_strength'])}, {f(s['base_attack_range'])}, "
                 f"{f(s.get('vision_radius', 8))}, {cp.get('gold', s.get('gold', 0))}u, {cp.get('gems', s.get('gems', 0))}u, "
                 f"{cp.get('respawn', s.get('respawn', 0))} }},")
lines.append('};')
lines.append('inline constexpr ItemDesign kItems[] = {')
for it in sorted(c['items'], key=lambda x: x['id']):
    res = it.get('result', -1) if it.get('combine_count', 0) else -1
    lines.append(f"    {{ \"{it['name']}\", {it['id']}, {it['cost']}u, {it.get('combine_count', 0)}u, {it.get('combine_cost', 0)}u, {res}, "
                 f"{it['health_points']}, {it['strength_points']}, {it['focus_points']}, {it['passive']}, {f(it['passive_magnitude'])}, "
                 f"{'true' if it['purchasable'] else 'false'} }},")
lines.append('};')
FAMS = ['monster', 'power', 'durability', 'treasure', 'jungle', 'home', 'bruiser']
STATS = ['strength', 'health', 'focus']
lines.append('// Per item: family (0-6, 255 none), stat (0 strength, 1 health, 2 focus, 255 none), kind (0 shard, 1 emblem, 4 other).')
lines.append('inline constexpr unsigned char kItemFamily[] = { ' + ', '.join(str(next((k for k, f in enumerate(FAMS) if it['name'].startswith(f + '_')), 255)) for it in sorted(c['items'], key=lambda x: x['id'])) + ' };')
lines.append('inline constexpr unsigned char kItemStat[] = { ' + ', '.join(str(next((k for k, st in enumerate(STATS) if it['name'].endswith('_of_' + st)), 255)) for it in sorted(c['items'], key=lambda x: x['id'])) + ' };')
lines.append('inline constexpr unsigned char kItemKind[] = { ' + ', '.join(('0' if '_shard_' in it['name'] else '1' if '_emblem_' in it['name'] else '4') for it in sorted(c['items'], key=lambda x: x['id'])) + ' };')
lines.append('inline constexpr PassiveDesign kPassives[] = {')
for p in sorted(c['passives'], key=lambda x: x['id']):
    lines.append(f"    {{ \"{p['name']}\", {p['id']}, {p['type']}, {f(p['magnitude'])} }},")
lines.append('};')
s = c['settings']
lines.append('inline constexpr Settings kSettings{ ' + ', '.join([
    str(s['capture_time']), str(s['camp_sleep_time']), str(s['respawn_time']), str(s['recall_time']), str(s['max_rounds']),
    str(s['winning_gems']), str(s['kill_gold']), f(s['submit_gem_duration_multiplier']), str(s['submit_gem_minimum_duration']),
    str(s['submit_gems_range']), str(s['ward_cooldown']), str(s['ward_vision_radius']), str(s['ward_placement_radius']),
    str(s['altar_lock_hits']), str(s['tp_crystal_time'])]) + ' };')
lines += ['', '}  // namespace zero::data', '']
OUT.write_bytes('\n'.join(lines).encode('utf-8'))
print(f'wrote {OUT}: {len(c["champions"])} champions, {len(c["camps"])} camps, {len(c["items"])} items, {len(c["passives"])} passives')
# Report camp fields the generator could not find (the camp rewards live in the stats block or at top level).
cp = c['camps'][0]
print('camp keys:', sorted(cp.keys()), 'stats keys:', sorted(cp['stats'].keys()))
