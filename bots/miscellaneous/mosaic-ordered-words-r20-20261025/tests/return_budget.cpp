unsigned checks = 0;
void check(bool ok, int line) {
    ++checks;
    if (!ok) {
        std::fprintf(stderr, "return-budget check %u failed at line %d\n", checks, line);
        std::abort();
    }
}
#define CHECK(condition) check(bool(condition), __LINE__)

State ready(double health = 10000) {
    return {health, 0, 0, true, 0, false, 0};
}

bool same_quote(const Quote& a, const Quote& b) {
    return a.valid == b.valid && a.safe == b.safe &&
           a.required_hp == b.required_hp && a.worst_loss == b.worst_loss &&
           a.first_reverse_endpoint == b.first_reverse_endpoint &&
           a.steps == b.steps && a.reason == b.reason &&
           a.shield_credited == b.shield_credited;
}

// Independent execution oracle: materialize the batches generated by the
// physical return itinerary, insert a refusal before one successful edge,
// then consume the actual shield one camp phase at a time. No Trace internals.
Cost loss_for(const std::vector<Cost>& outward, const State& state,
              std::size_t refused_edge) {
    std::vector<Cost> batches;
    const unsigned waits = state.additional_forced_waits +
                           (state.can_move_now ? 0u : 1u);
    for (unsigned i = 0; i < waits; ++i) batches.push_back(outward.back());
    std::size_t edge = 0;
    for (std::size_t origin = outward.size() - 1; origin > 0; --origin, ++edge) {
        if (edge == refused_edge) batches.push_back(outward[origin]);
        batches.push_back(outward[origin - 1]);
    }
    Cost shield = Cost(std::floor(state.shield));
    Cost loss = 0;
    for (std::size_t phase = 0; phase < batches.size(); ++phase) {
        const Cost active = phase < std::size_t(state.shield_phases) ? shield : 0;
        const Cost absorbed = std::min(active, batches[phase]);
        shield -= absorbed;
        loss += batches[phase] - absorbed;
    }
    return loss;
}

Cost oracle(const std::vector<Cost>& outward, const State& state) {
    Cost worst = loss_for(outward, state, outward.size());
    if (state.allow_one_refusal) {
        for (std::size_t edge = 0; edge + 1 < outward.size(); ++edge)
            worst = std::max(worst, loss_for(outward, state, edge));
    }
    return worst;
}

Trace trace_for(const std::vector<Cost>& damage) {
    Trace trace;
    CHECK(trace.reset_quiet({0, 0}, {0}));
    for (std::size_t i = 1; i < damage.size(); ++i)
        CHECK(trace.observe_step({int(i - 1), 0}, {int(i), 0},
                                 {damage[i]}, true) == Reason::ok);
    return trace;
}

void raw_catalog() {
    const Point p{10, 10};
    std::array<Threat, 12> catalog{};
    for (std::size_t i = 0; i < catalog.size(); ++i)
        catalog[i] = {{10, 10}, 0, double(i + 1)};
    CHECK(raw_damage_at(p, catalog).valid);
    CHECK(raw_damage_at(p, catalog).amount == 78);
    CHECK(raw_damage_at(p, std::span(catalog).first(8)).amount == 36);
    // All catalog members, including collateral beyond the local hot set,
    // contribute. Exact Chebyshev boundary, diagonal, and range0 matter.
    catalog[0] = {{13, 13}, 3, 100};
    catalog[1] = {{14, 10}, 3, 1000};
    CHECK(raw_damage_at(p, catalog).amount == 78 - 1 - 2 + 100);
    CHECK(raw_damage_at(p, std::span<const Threat>{}).amount == 0);
    const std::array fractional{Threat{{0, 0}, 1, 0.25},
                                Threat{{1, 1}, 1, 0.25}};
    CHECK(raw_damage_at({0, 0}, fractional).amount == 2);
    CHECK(raw_damage_at({0, 0}, fractional, 2).amount == 2);
    CHECK(raw_damage_at({0, 0}, fractional, 0).amount == 0);

    std::array<Threat, max_threats> complete{};
    for (auto& t : complete) t = {{1, 1}, 1, 1};
    CHECK(raw_damage_at({0, 0}, complete).amount == max_threats);
    const std::vector<Threat> oversized(max_threats + 1, {{0, 0}, 0, 0});
    CHECK(!raw_damage_at({0, 0}, oversized).valid);

    const double nan = std::numeric_limits<double>::quiet_NaN();
    const double inf = std::numeric_limits<double>::infinity();
    for (double bad : {-1.0, nan, inf, -inf}) {
        CHECK(!raw_damage_at(p, catalog, bad).valid);
        const std::array invalid{Threat{{1000, 1000}, 0, bad}};
        // Invalid catalog authority remains invalid even outside this tile.
        CHECK(!raw_damage_at(p, invalid).valid);
    }
    const std::array negative_range{Threat{{1000, 1000}, -1, 1}};
    CHECK(!raw_damage_at(p, negative_range).valid);
    const std::array overflow{Threat{{0, 0}, 0, double(cost_limit)}};
    CHECK(!raw_damage_at({0, 0}, overflow, 2).valid);
    const std::array float_overflow{Threat{{0, 0}, 0, 1e100}};
    CHECK(!raw_damage_at({0, 0}, float_overflow).valid);
    const std::array sum_overflow{
        Threat{{0, 0}, 0, double(cost_limit / 2)},
        Threat{{0, 0}, 0, double(cost_limit / 2)},
        Threat{{0, 0}, 0, double(cost_limit / 2)}};
    CHECK(!raw_damage_at({0, 0}, sum_overflow).valid);
    const std::array extreme{Threat{{std::numeric_limits<int>::max(),
                                   std::numeric_limits<int>::max()},
                                  std::numeric_limits<int>::max(), 7}};
    CHECK(raw_damage_at({std::numeric_limits<int>::min(),
                         std::numeric_limits<int>::min()}, extreme).amount == 0);
}

void history_and_admission() {
    Trace trace;
    CHECK(!trace.anchored() && !trace.valid() && trace.size() == 0);
    CHECK(trace.can_enter({0, 0}, {1, 0}, {1}) == Reason::unanchored);
    CHECK(trace.quote(ready()).reason == Reason::unanchored);
    CHECK(!trace.reset_quiet({0, 0}, {1}));
    CHECK(!trace.reset_quiet({0, 0}, {0, false}));
    CHECK(trace.reset_quiet({0, 0}, {0}));
    CHECK(trace.at({0, 0}) && trace.size() == 1);
    const auto initial_revision = trace.revision();
    CHECK(trace.can_enter({1, 0}, {2, 0}, {2}) == Reason::origin_mismatch);
    CHECK(trace.can_enter({0, 0}, {2, 0}, {2}) == Reason::not_ordinary_step);
    CHECK(trace.can_enter({0, 0}, {1, 0}, {0, false}) == Reason::invalid_damage);
    CHECK(trace.can_enter({0, 0}, {1, 0}, {cost_limit + 1}) == Reason::invalid_damage);
    CHECK(trace.can_enter({0, 0}, {0, 0}, {1}) == Reason::anchor_not_quiet);
    CHECK(trace.size() == 1 && trace.revision() == initial_revision);

    CHECK(trace.observe_step({0, 0}, {1, 1}, {10}, false) == Reason::ok);
    CHECK(trace.at({0, 0}) && trace.revision() == initial_revision);
    CHECK(trace.observe_step({1, 0}, {1, 1}, {10}, true) == Reason::origin_mismatch);
    CHECK(trace.observe_step({0, 0}, {2, 2}, {10}, true) == Reason::not_ordinary_step);
    CHECK(trace.at({0, 0}) && trace.revision() == initial_revision);

    CHECK(trace.observe_step({0, 0}, {1, 1}, {10}, true) == Reason::ok);
    CHECK(trace.observe_step({1, 1}, {2, 1}, {20}, true) == Reason::ok);
    CHECK(trace.observe_step({2, 1}, {2, 2}, {30}, true) == Reason::ok);
    CHECK(trace.size() == 4);
    CHECK(trace.observe_step({2, 2}, {2, 1}, {99}, true) == Reason::ok);
    CHECK(trace.size() == 3 && trace.at({2, 1}));
    State spent = ready();
    spent.can_move_now = false;
    CHECK(trace.quote(spent).worst_loss == 109);
    // Returning to a former interior vertex erases the loop and refreshes
    // its current damage. A genuinely quiet arrival replaces the anchor.
    CHECK(trace.observe_step({2, 1}, {1, 1}, {0}, true) == Reason::ok);
    CHECK(trace.size() == 1 && trace.at({1, 1}));
    const auto quiet = trace.quote(ready(0));
    CHECK(quiet.valid && !quiet.safe && quiet.required_hp == 1 && quiet.steps == 0);
    CHECK(quiet.first_reverse_endpoint == Point(1, 1));
    CHECK(!trace.reset_quiet({9, 9}, {4}));
    CHECK(trace.at({1, 1}));
    trace.invalidate();
    CHECK(!trace.anchored());
    CHECK(trace.quote(ready()).reason == Reason::unanchored);
    CHECK(trace.reset_quiet({4, 4}, {0}));
    trace.clear();
    CHECK(!trace.anchored());
}

void capacity_and_projection() {
    Trace trace;
    CHECK(trace.reset_quiet({0, 0}, {0}));
    for (std::size_t i = 1; i < Trace::capacity; ++i)
        CHECK(trace.observe_step({int(i - 1), 0}, {int(i), 0},
                                 {Cost(i)}, true) == Reason::ok);
    CHECK(trace.size() == Trace::capacity);
    const auto before = trace.quote(ready());
    const auto revision = trace.revision();
    CHECK(trace.can_enter({31, 0}, {32, 0}, {32}) == Reason::capacity);
    CHECK(trace.observe_step({31, 0}, {32, 0}, {32}, true) == Reason::capacity);
    CHECK(trace.size() == Trace::capacity && trace.at({31, 0}));
    CHECK(trace.revision() == revision && same_quote(before, trace.quote(ready())));
    CHECK(trace.quote_after_step({31, 0}, {32, 0}, {32}, ready()).reason == Reason::capacity);
    CHECK(trace.observe_step({31, 0}, {30, 0}, {30}, true) == Reason::ok);
    CHECK(trace.size() == Trace::capacity - 1);
    const auto projected = trace.quote_after_step({30, 0}, {30, 1}, {500}, ready());
    CHECK(projected.valid && projected.steps == Trace::capacity - 1);
    CHECK(trace.at({30, 0}) && trace.size() == Trace::capacity - 1);

    Trace small = trace_for({0, 11});
    const auto small_revision = small.revision();
    const auto first = small.quote(ready());
    State spent = ready(100);
    spent.can_move_now = false;
    const auto preview = small.quote_after_step({1, 0}, {2, 0}, {20}, spent);
    CHECK(preview.valid && preview.worst_loss == 31 && preview.required_hp == 32);
    CHECK(preview.first_reverse_endpoint == Point(1, 0) && preview.steps == 2);
    CHECK(small.size() == 2 && small.revision() == small_revision);
    CHECK(same_quote(first, small.quote(ready())));
    CHECK(small.quote_after_step({0, 0}, {1, 0}, {20}, spent).reason == Reason::origin_mismatch);
}

void repricing() {
    Trace trace;
    const std::array<Point, 4> geometry{
        Point{20, 30}, Point{20, 31}, Point{21, 32}, Point{22, 31}};
    CHECK(trace.reset_quiet(geometry[0], {0}));
    for (std::size_t i = 1; i < geometry.size(); ++i)
        CHECK(trace.observe_step(geometry[i - 1], geometry[i],
                                 {Cost(i * 10)}, true) == Reason::ok);
    const auto revision = trace.revision();
    const std::array<Damage, 4> replacement{
        Damage{0}, Damage{80}, Damage{5}, Damage{70}};
    CHECK(trace.refresh_damage(replacement) == Reason::ok);
    CHECK(trace.size() == geometry.size() && trace.current() == geometry.back());
    CHECK(trace.revision() == revision + 1);
    for (std::size_t i = 0; i < geometry.size(); ++i) {
        CHECK(trace.point(i) == geometry[i]);
        CHECK(trace.damage(i) == replacement[i].amount);
    }
    State state = ready();
    CHECK(trace.quote(state).worst_loss == 85);
    state.can_move_now = false;
    CHECK(trace.quote(state).worst_loss == 155);
    state.allow_one_refusal = true;
    CHECK(trace.quote(state).worst_loss == 235);
    state.shield = 91;
    state.shield_phases = 2;
    CHECK(trace.quote(state).worst_loss == oracle({0, 80, 5, 70}, state));

    // Repricing discovers bounds but does not claim a newly observed arrival.
    // Interior/current zero damage therefore preserves the actual itinerary.
    const std::array<Damage, 4> quieter{
        Damage{0}, Damage{80}, Damage{0}, Damage{0}};
    CHECK(trace.refresh_damage(quieter) == Reason::ok);
    CHECK(trace.size() == 4 && trace.current() == geometry.back());
    CHECK(trace.quote(ready()).worst_loss == 80);
    CHECK(trace.quote(ready()).first_reverse_endpoint == geometry[2]);

    const Trace reusable = trace;
    const auto check_invalid = [&](std::span<const Damage> bounds, Reason expected) {
        Trace attempt = reusable;
        const auto old_revision = attempt.revision();
        CHECK(attempt.refresh_damage(bounds) == expected);
        CHECK(!attempt.valid() && !attempt.anchored() && attempt.size() == 0);
        CHECK(attempt.revision() == old_revision + 1);
        CHECK(!attempt.quote(ready()).valid);
        CHECK(attempt.quote(ready()).reason == Reason::unanchored);
        CHECK(attempt.can_enter(geometry.back(), {23, 31}, {1}) == Reason::unanchored);
        // No partly repriced prefix remains an admissible certificate. Only
        // a new actual quiet anchor may restore the return geometry.
        CHECK(attempt.reset_quiet({100, 100}, {0}));
        CHECK(attempt.size() == 1 && attempt.current() == Point(100, 100));
    };

    std::array<Damage, 4> invalid = replacement;
    invalid[0] = {1};
    check_invalid(invalid, Reason::anchor_not_quiet);
    invalid = replacement;
    invalid.back() = {77, false};
    check_invalid(invalid, Reason::invalid_damage);
    invalid = replacement;
    invalid.back() = {cost_limit + 1};
    check_invalid(invalid, Reason::invalid_damage);
    check_invalid(std::span<const Damage>{}, Reason::invalid_damage);
    check_invalid(std::span(replacement).first(3), Reason::invalid_damage);
    const std::array<Damage, 5> too_long{
        Damage{0}, Damage{1}, Damage{2}, Damage{3}, Damage{4}};
    check_invalid(too_long, Reason::invalid_damage);

    Trace empty;
    const auto empty_revision = empty.revision();
    CHECK(empty.refresh_damage(std::span<const Damage>{}) == Reason::unanchored);
    CHECK(empty.revision() == empty_revision);

    // Validate all32 entries before publishing. An invalid final bound clears
    // even when every earlier entry would have been a large cost reduction.
    Trace full;
    CHECK(full.reset_quiet({0, 0}, {0}));
    for (std::size_t i = 1; i < Trace::capacity; ++i)
        CHECK(full.observe_step({int(i - 1), 0}, {int(i), 0},
                                {1000}, true) == Reason::ok);
    std::array<Damage, Trace::capacity> all{};
    for (std::size_t i = 1; i < all.size(); ++i) all[i] = {Cost(i)};
    CHECK(full.refresh_damage(all) == Reason::ok);
    for (std::size_t i = 0; i < all.size(); ++i) {
        CHECK(full.point(i) == Point(int(i), 0));
        CHECK(full.damage(i) == i);
    }
    all.back().valid = false;
    CHECK(full.refresh_damage(all) == Reason::invalid_damage);
    CHECK(full.size() == 0 && !full.quote(ready()).valid);
}

void meaningful_energy_examples() {
    // Native-loss sequence embedding, NOT a claim that these coordinates are
    // a quiet path in YBR. The final work input spent M: waiting at280 is real.
    Trace ryth;
    CHECK(ryth.reset_quiet({11, 11}, {0}));
    CHECK(ryth.observe_step({11, 11}, {12, 12}, {120}, true) == Reason::ok);
    CHECK(ryth.observe_step({12, 12}, {13, 13}, {120}, true) == Reason::ok);
    CHECK(ryth.observe_step({13, 13}, {14, 14}, {280}, true) == Reason::ok);
    CHECK(ryth.observe_step({14, 14}, {15, 15}, {280}, true) == Reason::ok);
    State state = ready(500);
    auto q = ryth.quote(state);
    CHECK(q.valid && !q.safe && q.worst_loss == 520 && q.required_hp == 521);
    CHECK(q.steps == 4 && q.first_reverse_endpoint == Point(14, 14));
    state.health = 780;
    state.can_move_now = false;
    q = ryth.quote(state);
    CHECK(q.valid && !q.safe && q.worst_loss == 800 && q.required_hp == 801);
    state.allow_one_refusal = true;
    CHECK(ryth.quote(state).worst_loss == 1080);
    state.can_move_now = true;
    CHECK(ryth.quote(state).worst_loss == 800);
    state.allow_one_refusal = false;
    state.health = 520.99;
    CHECK(!ryth.quote(state).safe);
    state.health = 521;
    CHECK(ryth.quote(state).safe);

    // Refusal may happen deep in the return, not only at today's endpoint.
    Trace late = trace_for({0, 90, 5, 1});
    state = ready(186);
    state.allow_one_refusal = true;
    CHECK(late.quote(state).worst_loss == 185 && late.quote(state).safe);
    state.health = 185;
    CHECK(!late.quote(state).safe);

    Trace timed = trace_for({0, 50, 20, 100});
    state = ready();
    state.shield = 100;
    state.shield_phases = 1;
    state.allow_one_refusal = true;
    const std::vector<Cost> itinerary{0, 50, 20, 100};
    // Duration1 shields the next batch. Its expiry makes the later50 refusal
    // worse than refusing at current100. Duration2 reverses that ordering.
    CHECK(loss_for(itinerary, state, 2) == 100);
    CHECK(loss_for(itinerary, state, 0) == 70);
    CHECK(timed.quote(state).worst_loss == 100 && timed.quote(state).shield_credited);
    state.shield_phases = 2;
    CHECK(loss_for(itinerary, state, 2) == 50);
    CHECK(loss_for(itinerary, state, 0) == 70);
    CHECK(timed.quote(state).worst_loss == 70);

    Trace one = trace_for({0, 40, 25});
    state = ready();
    state.shield = 100;
    state.shield_phases = 1;
    CHECK(one.quote(state).worst_loss == 0);
    state.can_move_now = false;
    CHECK(one.quote(state).worst_loss == 40);
    state.shield_phases = 0;
    CHECK(one.quote(state).worst_loss == 65 && !one.quote(state).shield_credited);
    state = ready(30.9);
    state.shield = 10.9;
    state.shield_phases = 1;
    CHECK(one.quote(state).worst_loss == 30 && !one.quote(state).safe);
    state.health = 31;
    CHECK(one.quote(state).safe);

    // A computation suspension can occur at an interior origin. The stated
    // conservative API ignores shield and charges each such delay at max risk.
    state = ready();
    state.shield = 10000;
    state.shield_phases = 100;
    state.compute_waits = 2;
    state.additional_forced_waits = 1;
    state.can_move_now = false;
    state.allow_one_refusal = true;
    CHECK(timed.quote(state).worst_loss == 570);
    CHECK(!timed.quote(state).shield_credited);
}

void invalid_states() {
    Trace trace = trace_for({0, 10});
    const double nan = std::numeric_limits<double>::quiet_NaN();
    const double inf = std::numeric_limits<double>::infinity();
    for (double bad : {-1.0, nan, inf, -inf, double(cost_limit) * 2}) {
        State state = ready();
        state.health = bad;
        CHECK(!trace.quote(state).valid && trace.quote(state).reason == Reason::invalid_state);
        state = ready();
        state.shield = bad;
        CHECK(!trace.quote(state).valid && trace.quote(state).reason == Reason::invalid_state);
    }
    State state = ready();
    state.shield_phases = -1;
    CHECK(trace.quote(state).reason == Reason::invalid_state);
    state = ready();
    state.additional_forced_waits = max_waits + 1;
    CHECK(trace.quote(state).reason == Reason::invalid_state);
    state = ready();
    state.compute_waits = max_waits + 1;
    CHECK(trace.quote(state).reason == Reason::invalid_state);
    state.additional_forced_waits = max_waits;
    state.compute_waits = max_waits;
    CHECK(trace.quote(state).valid);
}

void exhaustive_itineraries() {
    constexpr std::array<Cost, 3> damage{1, 7, 19};
    constexpr std::array<double, 4> shields{0, 1, 6, 31};
    // All small positive exposure paths. Zero arrivals deliberately establish
    // a new quiet anchor and are tested separately as lifecycle transitions.
    for (unsigned length = 1; length <= 4; ++length) {
        unsigned combinations = 1;
        for (unsigned i = 0; i < length; ++i) combinations *= 3;
        for (unsigned code = 0; code < combinations; ++code) {
            std::vector<Cost> path{0};
            unsigned digits = code;
            for (unsigned i = 0; i < length; ++i) {
                path.push_back(damage[digits % damage.size()]);
                digits /= unsigned(damage.size());
            }
            const Trace trace = trace_for(path);
            for (double shield : shields)
                for (int phases = 0; phases <= 4; ++phases)
                    for (unsigned spent = 0; spent < 2; ++spent)
                        for (unsigned waits = 0; waits <= 2; ++waits)
                            for (unsigned refusal = 0; refusal < 2; ++refusal) {
                                State state = ready();
                                state.shield = shield;
                                state.shield_phases = phases;
                                state.can_move_now = spent == 0;
                                state.additional_forced_waits = waits;
                                state.allow_one_refusal = refusal != 0;
                                const Cost expected = oracle(path, state);
                                const Quote q = trace.quote(state);
                                CHECK(q.valid && q.reason == Reason::ok);
                                CHECK(q.worst_loss == expected && q.required_hp == expected + 1);
                                CHECK(q.steps == length && q.first_reverse_endpoint == Point(int(length - 1), 0));
                                state.health = double(expected);
                                CHECK(!trace.quote(state).safe);
                                state.health = double(expected + 1);
                                CHECK(trace.quote(state).safe);
                            }
        }
    }
}
